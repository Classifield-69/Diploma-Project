import re


def preprocess_text(text: str) -> str:
    """
    Препроцесира ревю текст за подаване към tokenizer.texts_to_sequences().

    Стъпки (идентични с тренировъчния pipeline):
      1. Lowercase
      2. Премахване на URL-и
      3. Емоджи → <smile> / <sad> / <wink> токени
      4. Изолиране на ! и ? като отделни токени
      5. Премахване на останалата пунктуация (запазва букви, цифри, ! ? < >)
      6. Нормализация на whitespace
    """
    if not isinstance(text, str):
        return ''

    text = text.lower()

    text = re.sub(r'http\S+|www\.\S+', '', text)

    # Емоджи токени — трябва да е преди премахването на пунктуация
    text = re.sub(r'[:=][-]?[\)\]]+', ' <smile> ', text)
    text = re.sub(r'[:=][-]?[\(\[]+', ' <sad> ', text)
    text = re.sub(r';[-]?[\)\]]+', ' <wink> ', text)

    text = re.sub(r'!', ' ! ', text)
    text = re.sub(r'\?', ' ? ', text)

    # Запазваме: букви (кирилица + латиница), цифри, ! ? и <> за токените
    text = re.sub(r'[^а-яА-Яa-zA-Z0-9!?<>\s]', ' ', text)

    text = re.sub(r'\s+', ' ', text).strip()

    return text


